def _geometry_bounding_box_volume(input_paths: list[Path]) -> float:
    """Return the combined 3D bounding-box volume, or one when unavailable."""
    if not input_paths:
        return 1.0
    try:
        bounds = [pv.read(path).bounds for path in input_paths]
    except Exception:  # noqa: BLE001 - a bad preview path should not break controls.
        return 1.0
    spans = (
        max(bound[1] for bound in bounds) - min(bound[0] for bound in bounds),
        max(bound[3] for bound in bounds) - min(bound[2] for bound in bounds),
        max(bound[5] for bound in bounds) - min(bound[4] for bound in bounds),
    )
    volume = spans[0] * spans[1] * spans[2]
    return float(volume) if volume > 0 else 1.0


def _tetgen_volume_slider_options(input_paths: list[Path]) -> tuple[float, ...]:
    """Return logarithmic TetGen volume bounds scaled to the input geometry."""
    bounding_volume = _geometry_bounding_box_volume(input_paths)
    fractions = (
        1e-6,
        3e-6,
        1e-5,
        3e-5,
        1e-4,
        3e-4,
        1e-3,
        3e-3,
        1e-2,
        3e-2,
        1e-1,
    )
    return (0.0, *(bounding_volume * fraction for fraction in fractions))


def _format_volume_slider_value(value: float) -> str:
    """Format a TetGen volume bound for the Streamlit slider."""
    return "No limit" if value == 0 else f"{value:.3g}"


