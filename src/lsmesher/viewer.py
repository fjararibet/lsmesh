def _decimation_cli_flags(decimation: DecimationOptions3D) -> list[str]:
    """Translate decimation options into `lsmesher mesh` CLI flags."""
    if not decimation.enabled:
        return ["--no-decimate"]
    flags = [
        "--decimate-quality",
        str(decimation.quality_threshold),
        "--decimate-boundary-weight",
        str(decimation.boundary_weight),
        "--decimate-planar-weight",
        str(decimation.planar_weight),
    ]
    if decimation.target_edge_length is not None:
        flags.extend(
            ("--decimate-target-edge-length", str(decimation.target_edge_length))
        )
    elif decimation.target_faces is not None:
        flags.extend(("--decimate-target-faces", str(decimation.target_faces)))
    else:
        flags.extend(
            (
                "--decimate-target-total-faces",
                str(decimation.target_total_faces or DEFAULT_TARGET_TOTAL_FACES),
            )
        )
    if decimation.optimal_placement:
        flags.append("--decimate-optimal-placement")
    flags.append(
        "--decimate-preserve-boundary"
        if decimation.preserve_boundary
        else "--no-decimate-preserve-boundary"
    )
    flags.append(
        "--decimate-planar-quadric"
        if decimation.planar_quadric
        else "--no-decimate-planar-quadric"
    )
    return flags


def _mesher_cli_flags(options: MesherOptions) -> list[str]:
    """Translate mesher quality options into `lsmesher mesh` CLI flags."""
    flags = [
        "--triangle-min-angle",
        str(options.triangle_min_angle),
        "--tetgen-quality-ratio",
        str(options.tetgen_quality_ratio),
        "--tetgen-min-dihedral",
        str(options.tetgen_min_dihedral),
        "--bottom-margin",
        str(options.bottom_margin),
        "--seam-protection-rings",
        str(options.seam_protection_rings),
    ]
    if options.tetgen_max_volume is not None:
        flags.extend(("--tetgen-max-volume", str(options.tetgen_max_volume)))
    return flags


def _run_pipeline(  # noqa: PLR0913
    input_paths: list[Path],
    *,
    epsilon: float,
    output_format: str,
    run_mesher: bool,
    output_path: Path | None = None,
    decimation: DecimationOptions3D | None = None,
    mesher: MesherOptions | None = None,
) -> Path:
    """Run the meshing pipeline in a subprocess and return the output path.

    The pipeline runs via ``lsmesher mesh`` in a child process on purpose:
    pymeshlab's bundled Qt runtime binds thread-local state to whichever
    thread first loads it, and Streamlit script threads are short-lived, so
    running it in the viewer process corrupts the heap and eventually aborts
    the whole viewer (glibc "corrupted size vs. prev_size" /
    "malloc_consolidate" errors). A subprocess also turns any native crash
    into a readable error instead of killing the viewer.
    """
    suffix = f".{output_format}"
    output_path = (
        output_path
        or Path(tempfile.mkdtemp(prefix="lsmesher-viewer-")) / f"mesh{suffix}"
    )
    output_path.parent.mkdir(parents=True, exist_ok=True)

    command = [
        sys.executable,
        "-m",
        "lsmesher.cli",
        "mesh",
        *[str(path) for path in input_paths],
        "--epsilon",
        str(epsilon),
        "--format",
        output_format,
        "--out",
        str(output_path),
        *([] if run_mesher else ["--no-mesh"]),
        *_mesher_cli_flags(mesher or MesherOptions()),
        *_decimation_cli_flags(decimation or DecimationOptions3D()),
    ]
    result = subprocess.run(command, capture_output=True, text=True, check=False)
    if result.stdout:
        sys.stdout.write(result.stdout)
    if result.returncode != 0:
        message = "\n\n".join(
            part
            for part in (
                f"Meshing pipeline failed with exit code {result.returncode}.",
                f"stdout:\n{result.stdout}" if result.stdout else "",
                f"stderr:\n{result.stderr}" if result.stderr else "",
            )
            if part
        )
        raise RuntimeError(message)

    return output_path


def _run_2d_polygon_preview(
    input_paths: list[Path],
    *,
    epsilon: float,
    output_path: Path | None = None,
) -> Path:
    """Write the pre-mesh 2D pipeline polygon to a temporary VTP file."""
    dimension = detect_dimension(str(input_paths[0]))
    if dimension != 2:
        message = "Pipeline polygon preview is only available for 2D VTP inputs."
        raise ValueError(message)

    geometry = build_2d_poly_geometry(
        read_2d_layers(input_paths),
        epsilon=epsilon,
        detect_holes=False,
    )
    output_path = (
        output_path
        or Path(tempfile.mkdtemp(prefix="lsmesher-polygon-")) / "polygon.vtp"
    )
    output_path.parent.mkdir(parents=True, exist_ok=True)
    write_vtp_2d(
        output_path,
        geometry.points,
        [Face(edge.as_tuple()) for edge in geometry.edges],
    )
    return output_path


