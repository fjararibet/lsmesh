def _decimation_sidebar_controls(defaults: DecimationOptions3D) -> DecimationOptions3D:
    """Render 3D decimation controls in the sidebar and return the options."""
    st.subheader("3D decimation")
    enabled = st.toggle(
        "Decimate surfaces",
        value=defaults.enabled,
        key="decimate_surfaces",
        help=(
            "Simplify the extracted surfaces (quadric edge collapse) before "
            "TetGen runs. **On:** far fewer triangles, so tetrahedralization "
            "and rendering are much faster and the volume mesh is smaller — "
            "at the cost of smoothing out geometric detail finer than the "
            "target resolution. **Off:** the surfaces keep their full "
            "level-set resolution — most faithful geometry, but the largest "
            "and slowest meshes. Safety rails in both cases: material "
            "junction curves and domain-wall traces are always preserved "
            "exactly so layers keep conforming, and faces near self-touching "
            "pinch-off seams are never decimated."
        ),
    )
    if not enabled:
        return DecimationOptions3D(enabled=False)

    target_mode = st.radio(
        "Decimation target",
        ("Total face budget", "Target edge length"),
        horizontal=True,
        help=(
            "The total budget is distributed across the unique conforming patch "
            "complex by physical surface area. Edge length instead specifies an "
            "approximate spatial resolution in model units."
        ),
    )
    target_total_faces: int | None = None
    target_edge_length: float | None = None
    if target_mode == "Total face budget":
        face_budgets = (
            1_000,
            2_000,
            4_000,
            5_600,
            8_000,
            12_000,
            20_000,
            50_000,
            100_000,
        )
        default_budget = defaults.target_total_faces or DEFAULT_TARGET_TOTAL_FACES
        target_total_faces = st.select_slider(
            "Target total surface faces",
            options=face_budgets,
            value=min(face_budgets, key=lambda value: abs(value - default_budget)),
            help=(
                "Requested faces across unique decimatable patches. Each patch "
                "receives a share proportional to its true 3D area. Protected "
                "seams, fixed boundaries, and safety retries can make the achieved "
                "count higher."
            ),
        )
    else:
        target_edge_length = float(
            st.number_input(
                "Target triangle edge length",
                min_value=1e-6,
                value=float(defaults.target_edge_length or 0.25),
                format="%.6g",
                help=(
                    "Approximate edge length in model units. Patch targets are "
                    "derived from the area of equilateral triangles of this size."
                ),
            )
        )
    quality_threshold = st.slider(
        "Quality threshold",
        min_value=0.1,
        max_value=1.0,
        value=float(min(max(defaults.quality_threshold, 0.1), 1.0)),
        step=0.05,
        help=(
            "How strongly the collapse cost penalizes badly shaped triangles "
            "(1 ≈ demand near-equilateral, 0.1 ≈ tolerate slivers). This "
            "trades triangle shape against how far collapse can proceed, but "
            "it is *not* a simplification throttle: on flat regions any value "
            "from 0.1 to 1.0 reaches the same face count. **Higher:** "
            "well-shaped triangles that give TetGen better tetrahedra. "
            "**Lower:** tolerates skinnier triangles. Note: a value of 0 "
            "removes the shape term entirely and paradoxically stalls "
            "simplification on flat, zero-error regions — so the slider "
            "starts at 0.1."
        ),
    )
    preserve_boundary = st.toggle(
        "Preserve patch boundaries",
        value=defaults.preserve_boundary,
        help=(
            "Keep the patch boundary curves — material junction curves and "
            "the traces where surfaces meet the domain walls — exactly "
            "fixed during decimation. **On (recommended):** decimated "
            "layers keep conforming exactly where they meet, which the "
            "rest of the pipeline depends on. **Off:** ⚠️ boundaries may "
            "move or lose vertices, so adjacent layers stop matching "
            "triangle-for-triangle. Expect holes at material interfaces, "
            "“Cannot close 3D surface” errors when boundary points drift "
            "off the domain walls, wrong material region assignments, and "
            "TetGen failures. Only consider disabling for single-surface "
            "experiments where maximum simplification matters more than a "
            "valid volume mesh."
        ),
    )
    boundary_weight = defaults.boundary_weight
    if not preserve_boundary:
        st.warning(
            "Patch boundaries are free to move: layers may stop conforming, "
            "causing holes at material interfaces, “Cannot close 3D "
            "surface” errors, or TetGen failures.",
            icon="⚠️",
        )
        boundary_weight_options = (
            0.1,
            0.5,
            1.0,
            5.0,
            10.0,
            50.0,
            100.0,
            500.0,
            1000.0,
        )
        boundary_weight = st.select_slider(
            "Boundary weight",
            options=boundary_weight_options,
            value=min(
                boundary_weight_options,
                key=lambda option: abs(option - defaults.boundary_weight),
            ),
            help=(
                "How important the patch boundary is while it is free to "
                "move (only used when Preserve patch boundaries is off). "
                "1 treats the boundary like any other part of the surface; "
                "the effect grows on a log scale, so the slider stops do "
                "too. **Higher:** removes fewer boundary vertices and keeps "
                "junction curves closer to their original shape — safer, "
                "but less simplification there. **Lower:** simplifies the "
                "boundary as aggressively as the interior, maximizing face "
                "reduction but distorting junctions and wall traces the "
                "most."
            ),
        )
    optimal_placement = st.toggle(
        "Optimal vertex placement",
        value=defaults.optimal_placement,
        help=(
            "Where the merged vertex lands when an edge collapses. **On:** "
            "placed at the error-minimizing position, giving a smoother, "
            "more accurate surface for the same face count — but new "
            "vertices move off the original surface, which raises the risk "
            "of self-intersections (and TetGen failures) where two sheets "
            "of the surface run close together. **Off:** vertices stay at "
            "original surface positions — slightly blockier result, but "
            "safer for narrow gaps and near-touching films."
        ),
    )
    planar_quadric = st.toggle(
        "Planar quadric",
        value=defaults.planar_quadric,
        help=(
            "In perfectly flat regions the standard quadric error is zero, "
            "so the simplifier collapses them arbitrarily — often into a "
            "few long, badly shaped triangles. This option adds a small "
            "shape-regularizing term in flat areas. **On:** flat walls and "
            "floors keep a cleaner, better-shaped triangulation (as a side "
            "effect, somewhat more triangles are preserved there), which "
            "gives TetGen better elements. **Off:** flat regions simplify "
            "as aggressively as possible — fewer faces, but sliver "
            "triangles can appear and degrade tetrahedron quality."
        ),
    )
    planar_weight_options = (0.0, 0.0005, 0.001, 0.005, 0.01, 0.05, 0.1, 0.5, 1.0)
    planar_weight = st.select_slider(
        "Planar weight",
        options=planar_weight_options,
        value=min(
            planar_weight_options,
            key=lambda option: abs(option - defaults.planar_weight),
        ),
        help=(
            "Strength of the flat-region regularization (only used when "
            "Planar quadric is on). The effect grows on a log scale, so "
            "the slider stops do too: 0 disables the term entirely; 1 "
            "preserves flat regions about as strongly as a real patch "
            "border. **Higher:** flat areas keep more, better-shaped "
            "triangles — better element quality, slightly more faces. "
            "**Lower:** flat areas are simplified more aggressively — "
            "fewer faces, higher sliver risk. The 0.001 default adds just "
            "enough regularization to keep flat-area triangles reasonable."
        ),
    )
    return DecimationOptions3D(
        enabled=True,
        target_total_faces=target_total_faces,
        target_edge_length=target_edge_length,
        quality_threshold=float(quality_threshold),
        preserve_boundary=preserve_boundary,
        boundary_weight=float(boundary_weight),
        optimal_placement=optimal_placement,
        planar_quadric=planar_quadric,
        planar_weight=float(planar_weight),
    )


def app() -> None:  # noqa: C901, PLR0912, PLR0915
    """Render the Streamlit application."""
    st.set_page_config(page_title="lsmesher live viewer", layout="wide")

    root = Path.cwd()
    st.session_state.setdefault("preset_paths", [])
    st.session_state.setdefault("preset_message", "")
    st.session_state.setdefault("preset_name", "")
    st.session_state.setdefault("preset_description", "")
    st.session_state.setdefault("preset_dimension", None)
    preview_modes = ["Processed mesh", "Raw selected files"]
    if st.session_state.get("preview_mode") not in preview_modes:
        st.session_state["preview_mode"] = preview_modes[0]

    selected_paths: list[Path] = []
    selected_preset: Preset | None = None
    presets = _presets(root)
    preset_dimension = st.sidebar.radio(
        "Preset dimension",
        ["2D", "3D"],
        index=1,
        horizontal=True,
    )
    expected_dimension = int(preset_dimension[0])
    presets = [preset for preset in presets if preset.dimension == expected_dimension]
    if not presets:
        st.sidebar.info("No presets found.")
    else:
        preset_by_name = {preset.name: preset for preset in presets}
        selected_preset_name = st.sidebar.selectbox(
            "Preset",
            list(preset_by_name),
        )
        selected_preset = preset_by_name[selected_preset_name]
        if selected_preset_name != st.session_state["preset_name"]:
            st.session_state["preset_paths"] = []
            st.session_state["preset_message"] = ""
            st.session_state["preset_name"] = selected_preset.name
            st.session_state["preset_description"] = selected_preset.description
            st.session_state["preset_dimension"] = selected_preset.dimension
            if selected_preset.files:
                with st.spinner(f"Loading {selected_preset.name}..."):
                    selected_paths, message = _load_preset(selected_preset, root)
                st.session_state["preset_paths"] = [
                    str(path) for path in selected_paths
                ]
                st.session_state["preset_message"] = message
            st.rerun()
    selected_paths = [Path(path) for path in st.session_state["preset_paths"]]

    if st.sidebar.button("✕ Clear active preset"):
        st.session_state["preset_paths"] = []
        st.session_state["preset_message"] = ""
        st.session_state["preset_name"] = ""
        st.session_state["preset_description"] = ""
        st.session_state["preset_dimension"] = None
        st.rerun()

    viewer_tab, config_tab = st.sidebar.tabs(["Viewer", "Config"])
    config_values: dict[str, str] = {}
    with config_tab:
        if selected_preset is not None and selected_preset.config is not None:
            st.subheader("Preset config")
            config_values = {
                entry.key: st.text_input(
                    entry.key,
                    value=entry.value,
                    key=(
                        f"preset_config_{_slug(selected_preset.name)}_"
                        f"{_slug(entry.key)}_{_slug(entry.value)}"
                    ),
                )
                for entry in _read_config_entries(selected_preset.config)
            }
            if st.button("⚙ Generate preset"):
                with st.spinner(f"Generating {selected_preset.name}..."):
                    selected_paths, message = _load_preset(
                        selected_preset,
                        root,
                        config_values=config_values,
                        force_generate=True,
                        output_dir=_preset_output_dir(root, selected_preset.name)
                        / "generated_preset",
                    )
                st.session_state["preset_paths"] = [
                    str(path) for path in selected_paths
                ]
                st.session_state["preset_message"] = message
                st.rerun()
        else:
            st.info("This preset has no editable config.")

    with viewer_tab:
        st.header("Inputs")
        epsilon_exponent = st.select_slider(
            "2D collinear epsilon exponent",
            options=tuple(range(-8, 0)),
            value=-6,
            format_func=lambda exponent: f"10^{exponent}",
            help=("Epsilon is 10 raised to this exponent, from 10^-8 through 10^-1."),
        )
        epsilon = 10.0 ** int(epsilon_exponent)
        preview_mode = st.radio(
            "Preview",
            preview_modes,
            key="preview_mode",
        )
        renderer = st.radio(
            "Renderer",
            ["PyVista PNG", "Plotly interactive"],
            help="PyVista PNG renders server-side and handles large 2D meshes better.",
        )
        processed_display = "Filled triangles"
        if preview_mode == "Processed mesh":
            processed_display = st.radio(
                "Processed mesh display",
                ["Filled triangles", "Wireframe edges"],
                help="Wireframe edges skips triangle fill and draws all cell edges, including interior triangle edges.",
            )
        max_wireframe_edges = DEFAULT_MAX_WIREFRAME_EDGES
        if processed_display == "Wireframe edges":
            max_wireframe_edges = st.slider(
                "Max wireframe edges",
                min_value=1_000,
                max_value=500_000,
                value=DEFAULT_MAX_WIREFRAME_EDGES,
                step=1_000,
                help="Higher values show more edges but can make Plotly/Streamlit slow on large meshes.",
            )
        run_mesher = st.toggle(
            "Run mesher",
            value=True,
            help="Runs Triangle for 2D presets and TetGen for 3D presets.",
        )
        dimension = st.session_state["preset_dimension"] or expected_dimension
        output_format = "vtu" if dimension == 2 or run_mesher else "vtp"
        mesher = _mesher_quality_sidebar_controls(
            dimension, MesherOptions(), selected_paths
        )
        decimation = DecimationOptions3D()
        if dimension == 3:
            decimation = _decimation_sidebar_controls(DecimationOptions3D())
        st.button("↻ Recompute outputs")
        show_edges = st.toggle("Show edges", value=True)
        color = st.color_picker("Mesh color", "#8dd3ff")
    if not selected_paths:
        st.info("Generate or select a preset.")
        return

    title = st.session_state["preset_name"] or selected_paths[0].stem
    st.subheader(title)
    output_dir = _preset_output_dir(root, title)
    st.caption(f"Generated files: `{output_dir}`")

    try:
        if preview_mode == "Raw selected files":
            for path in selected_paths:
                if renderer == "PyVista PNG":
                    _render_mesh_png(
                        path,
                        options=PyVistaPngOptions(
                            show_edges=show_edges,
                            color=color,
                        ),
                    )
                else:
                    _render_mesh(
                        path,
                        options=MeshRenderOptions(show_edges=show_edges, color=color),
                    )
        elif preview_mode == "Pipeline polygon":
            output_path = _write_2d_polygon_preview_output(
                selected_paths,
                epsilon=epsilon,
                output_dir=output_dir / "pipeline_polygon",
            )
            if renderer == "PyVista PNG":
                _render_mesh_png(
                    output_path,
                    options=PyVistaPngOptions(show_edges=True, color=color),
                )
            else:
                _render_mesh(
                    output_path,
                    options=MeshRenderOptions(show_edges=show_edges, color=color),
                )
        else:
            processed_options = ProcessedMeshOptions(
                epsilon=epsilon,
                output_format=output_format,
                run_mesher=run_mesher,
                decimation=decimation,
                mesher=mesher,
            )
            output_path: Path | None = None
            attempts = _processed_mesh_retry_options(selected_paths, processed_options)
            for attempt_index, (label, attempt_options, retry_reason) in enumerate(
                attempts,
                start=1,
            ):
                if retry_reason is not None:
                    st.warning(
                        f"Retrying processed mesh with {label}: {retry_reason}",
                    )
                try:
                    output_path = _write_processed_mesh_output(
                        selected_paths,
                        options=attempt_options,
                        output_dir=output_dir / "processed_mesh",
                    )
                    if attempt_index > 1:
                        st.success(f"Retry succeeded with {label}.")
                    break
                except Exception as exc:
                    if attempt_index < len(attempts):
                        st.warning(
                            f"Processed mesh attempt {attempt_index} failed with "
                            f"{label}: {_exception_summary(exc)}"
                        )
                    else:
                        st.error(_processed_mesh_failure_guidance(processed_options))
                        raise
            output_path = cast("Path", output_path)
            wireframe = processed_display == "Wireframe edges"
            if renderer == "PyVista PNG":
                _render_mesh_png(
                    output_path,
                    options=PyVistaPngOptions(
                        show_edges=show_edges or wireframe,
                        color=color,
                        fill_surfaces=not wireframe,
                        all_cell_edges=wireframe,
                    ),
                )
            else:
                _render_mesh(
                    output_path,
                    options=MeshRenderOptions(
                        show_edges=show_edges or wireframe,
                        color=color,
                        fill_surfaces=not wireframe,
                        all_cell_edges=wireframe,
                        max_edges=max_wireframe_edges if wireframe else None,
                    ),
                )
            _show_tetgen_log(output_path)
            _show_decimation_report(output_path)
            if selected_preset is not None:
                _show_preset_data_download(
                    selected_preset,
                    root,
                    output_path=output_path,
                    raw_files=selected_paths,
                    config_values=config_values,
                )
    except Exception as exc:  # noqa: BLE001 - Streamlit should display pipeline errors.
        st.exception(exc)


def main() -> None:
    """Launch the Streamlit viewer from the console script."""
    os.environ.setdefault("PYVISTA_OFF_SCREEN", "true")
    viewer_path = Path(__file__).resolve()
    sys.argv = ["streamlit", "run", str(viewer_path), *sys.argv[1:]]

    streamlit_main()


if __name__ == "__main__":
    app()
